/**
 * Updates only the horizontal platform logo — does not touch app icons / favicons.
 * Usage: node scripts/update-logo-only.mjs [path-to-logo-source]
 *
 * Source files are usually JPEG on black. We:
 *  - knock out near-black pixels for the light-UI lockup
 *  - keep a black-background lockup for dark UI (front desk)
 */
import { writeFile, mkdir } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, "..")
const brandDir = path.join(root, "public", "brand")
const adminBrandDir = path.join(root, "..", "..", "Community-app-admin", "public", "brand")
const mobileBrandDir = path.join(root, "..", "..", "Community_Hub_Mobile", "assets", "brand")

const DEFAULT_SOURCE =
  "/home/nansi/.cursor/projects/home-nansi-Work/assets/c__Users_HomePC_AppData_Roaming_Cursor_User_workspaceStorage_2a19be2fbd444bced0afbecccf4f1fcf_images_RED-Nairobi-Up_and_Running_-_PR-f0363563-26b2-4f05-ae47-f05e4aee11dc.png"

const TARGET_WIDTH = 1000

function isKnockoutPixel(r, g, b) {
  const max = Math.max(r, g, b)
  const reddish = r > 40 && r > g * 1.25 && r > b * 1.25
  if (reddish) return false
  return max < 36
}

async function knockoutBlack(sourcePath) {
  const { data, info } = await sharp(sourcePath)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })

  const { width, height, channels } = info
  for (let i = 0; i < data.length; i += channels) {
    if (isKnockoutPixel(data[i], data[i + 1], data[i + 2])) {
      data[i] = 0
      data[i + 1] = 0
      data[i + 2] = 0
      data[i + 3] = 0
    }
  }

  return sharp(data, { raw: { width, height, channels } })
    .png()
    .toBuffer()
}

async function buildLogoPng(sourcePath) {
  const knocked = await knockoutBlack(sourcePath)
  const trimmed = await sharp(knocked).trim({ threshold: 8 }).png().toBuffer()
  const meta = await sharp(trimmed).metadata()
  const height = Math.round((TARGET_WIDTH * meta.height) / meta.width)
  return sharp(trimmed)
    .resize(TARGET_WIDTH, height, { fit: "fill", kernel: sharp.kernel.lanczos3 })
    .png({ compressionLevel: 9 })
    .toBuffer()
}

async function buildOnDarkPng(sourcePath) {
  const trimmed = await sharp(sourcePath).trim({ threshold: 8 }).png().toBuffer()
  const meta = await sharp(trimmed).metadata()
  const height = Math.round((TARGET_WIDTH * meta.height) / meta.width)
  return sharp(trimmed)
    .resize(TARGET_WIDTH, height, { fit: "fill", kernel: sharp.kernel.lanczos3 })
    .png({ compressionLevel: 9 })
    .toBuffer()
}

async function cropMark(logoPng) {
  const meta = await sharp(logoPng).metadata()
  const size = meta.height
  return sharp(logoPng)
    .extract({ left: 0, top: 0, width: size, height: size })
    .png({ compressionLevel: 9 })
    .toBuffer()
}

function logoSvg(viewBoxWidth, viewBoxHeight) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${viewBoxWidth} ${viewBoxHeight}" role="img" aria-label="Impact Hub Nairobi">
  <image width="${viewBoxWidth}" height="${viewBoxHeight}" href="/brand/impact-hub-nairobi-logo.png" />
</svg>
`
}

async function writeBrandMeta(width, height, tile) {
  const content = `/** Generated by scripts/generate-brand-assets.mjs — do not edit by hand. */
export const BRAND_LOGO_PATH = "/brand/impact-hub-nairobi-logo.png"
export const BRAND_LOGO_SVG_PATH = "/brand/impact-hub-nairobi-logo.svg"
export const BRAND_LOGO_ON_DARK_PATH = "/brand/impact-hub-nairobi-logo-on-dark.png"
export const BRAND_MARK_PATH = "/brand/impact-hub-mark.png"
export const BRAND_MARK_SVG_PATH = "/brand/impact-hub-mark.svg"
export const BRAND_APP_ICON_SVG_PATH = "/brand/impact-hub-app-icon.svg"

/** Full horizontal logo dimensions (source PNG). */
export const BRAND_LOGO_WIDTH = ${width}
export const BRAND_LOGO_HEIGHT = ${height}

/** Square tile width in the full logo (left mark). */
export const BRAND_LOGO_TILE_SIZE = ${tile}

export const BRAND_LOGO_ASPECT_RATIO = ${width} / ${height}
export const BRAND_LOGO_TILE_RATIO = ${tile} / ${width}
`
  await writeFile(path.join(root, "lib", "brand-meta.ts"), content)
}

async function main() {
  const sourcePath = process.argv[2] ?? DEFAULT_SOURCE
  await mkdir(brandDir, { recursive: true })
  await mkdir(adminBrandDir, { recursive: true })
  await mkdir(mobileBrandDir, { recursive: true })

  const logoPng = await buildLogoPng(sourcePath)
  const onDarkPng = await buildOnDarkPng(sourcePath)
  const markPng = await cropMark(logoPng)
  const meta = await sharp(logoPng).metadata()
  const width = meta.width
  const height = meta.height
  const tile = height

  const files = {
    "impact-hub-nairobi-logo.png": logoPng,
    "impact-hub-nairobi-logo-on-dark.png": onDarkPng,
    "impact-hub-nairobi-logo.svg": Buffer.from(logoSvg(width, height)),
  }

  for (const [name, buf] of Object.entries(files)) {
    await writeFile(path.join(brandDir, name), buf)
    await writeFile(path.join(adminBrandDir, name), buf)
  }

  await writeFile(path.join(brandDir, "impact-hub-nairobi-mark-lockup.png"), markPng)
  await writeFile(path.join(adminBrandDir, "impact-hub-nairobi-mark-lockup.png"), markPng)
  await writeFile(path.join(mobileBrandDir, "impact-hub-nairobi-logo.png"), logoPng)
  await writeFile(path.join(mobileBrandDir, "impact-hub-nairobi-logo-on-dark.png"), onDarkPng)
  await writeFile(path.join(mobileBrandDir, "impact-hub-mark.png"), markPng)

  await writeBrandMeta(width, height, tile)

  const { spawn } = await import("node:child_process")
  await new Promise((resolve, reject) => {
    const child = spawn("node", ["scripts/generate-email-logo-data.mjs"], {
      cwd: root,
      stdio: "inherit",
    })
    child.on("error", reject)
    child.on("close", (code) => (code === 0 ? resolve() : reject(new Error(`email logo data exit ${code}`))))
  })

  console.log(`Brand logo: ${width}×${height}px`)
  console.log("Wrote Community-App, Community-app-admin, and Community_Hub_Mobile logos")
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
