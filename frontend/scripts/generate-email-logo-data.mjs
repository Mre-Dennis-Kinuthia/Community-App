/**
 * Embeds the brand PNG as base64 in a TS module so Vercel serverless can attach it to emails
 * (public/ is not available via fs at runtime on Lambda).
 *
 * Run: node scripts/generate-email-logo-data.mjs
 * Wired into postinstall + build + brand:logo.
 *
 * Writes Community-app-admin only when that sibling repo exists (local monorepo).
 * On Vercel member-app deploys, admin is absent — skip without failing.
 */
import { access, mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, "..")
const adminRoot = path.join(root, "..", "Community-app-admin")

const SOURCE = path.join(root, "public", "brand", "impact-hub-nairobi-logo.png")

const OUTPUTS = [
  { path: path.join(root, "lib", "email", "brand-logo-data.ts"), required: true },
  {
    path: path.join(adminRoot, "lib", "email", "brand-logo-data.ts"),
    required: false,
    requireDir: adminRoot,
  },
]

async function pathExists(target) {
  try {
    await access(target)
    return true
  } catch {
    return false
  }
}

async function generateForOutput(output, base64) {
  if (!output.required) {
    const parent = output.requireDir ?? path.dirname(output.path)
    if (!(await pathExists(parent))) {
      console.log("[email-logo] Skipping (repo not present):", output.path)
      return
    }
  }

  await mkdir(path.dirname(output.path), { recursive: true })
  const content = `/** Generated by scripts/generate-email-logo-data.mjs — do not edit by hand. */
export const EMAIL_LOGO_PNG_BASE64 = "${base64}"
`
  await writeFile(output.path, content, "utf8")
  console.log("[email-logo] Wrote", output.path)
}

async function main() {
  const buffer = await readFile(SOURCE)
  const base64 = buffer.toString("base64")
  for (const output of OUTPUTS) {
    await generateForOutput(output, base64)
  }
  console.log(`[email-logo] Embedded ${buffer.length} bytes (${base64.length} base64 chars)`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
